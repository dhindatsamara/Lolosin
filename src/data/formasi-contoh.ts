/** Format rupiah singkat: 5100000 jadi "Rp5,1 jt". */
export function formatGajiSingkat(nilai: number): string {
  const juta = nilai / 1_000_000
  const teks = juta.toLocaleString('id-ID', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 1,
  })
  return `Rp${teks} jt`
}

/** Format rupiah lengkap: 5100000 jadi "Rp5.100.000". */
export function formatGajiLengkap(nilai: number): string {
  return `Rp${nilai.toLocaleString('id-ID')}`
}
